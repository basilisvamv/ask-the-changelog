import { test } from 'node:test';
import assert from 'node:assert/strict';
import { normalizePlan, diffPlans, checkExtraction, summarize, toIsoDate } from '../src/diff.js';

const snap = (plans) => ({ plans: plans.map(normalizePlan) });
const item = (date, title, summary = 'Short summary.') => ({ date, title, category: 'model', summary });

test('first run: only record, no alerts', () => {
  const r = diffPlans(null, snap([item('2026-11-01', 'Model A')]));
  assert.equal(r.baseline, true);
  assert.deepEqual(r.changes, []);
});

test('new announcement is reported, old ones are not', () => {
  const prev = snap([item('2026-11-01', 'Model A')]);
  const next = snap([item('2026-11-14', 'Model B'), item('2026-11-01', 'Model A')]);
  const r = diffPlans(prev, next);
  assert.equal(r.changes.length, 1);
  assert.equal(r.changes[0].type, 'added');
  assert.equal(r.changes[0].title, 'Model B');
});

test('same announcements give no changes', () => {
  const same = [item('2026-11-01', 'Model A'), item('2026-10-30', 'Model B')];
  assert.deepEqual(diffPlans(snap(same), snap(same)).changes, []);
});

test('same title on another date is a new announcement', () => {
  const prev = snap([item('2026-11-01', 'Update')]);
  const next = snap([item('2026-11-14', 'Update'), item('2026-11-01', 'Update')]);
  const r = diffPlans(prev, next);
  assert.equal(r.changes.length, 1);
  assert.equal(r.changes[0].date, '2026-11-14');
});

test('title is compared without extra spaces and case', () => {
  const r = diffPlans(snap([item('2026-11-01', '  Model A ')]), snap([item('2026-11-01', 'model a')]));
  assert.deepEqual(r.changes, []);
});

test('straight and typographic apostrophe count as the same title', () => {
  const r = diffPlans(snap([item('2026-11-09', "We've launched Claude Fable 5.2")]), snap([item('2026-11-09', 'We’ve launched Claude Fable 5.2')]));
  assert.deepEqual(r.changes, []);
});

test('older announcements with another title are not reported', () => {
  const prev = snap([item('2026-11-09', 'Fable'), item('2026-11-03', 'Text generated by X'), item('2026-11-02', 'Long conversations')]);
  const next = snap([item('2026-11-09', 'Fable'), item('2026-11-03', 'Text watermark for X'), item('2026-11-02', 'Message threads')]);
  assert.deepEqual(diffPlans(prev, next).changes, []);
});

test('announcement without date is ignored when the baseline has dates', () => {
  const prev = snap([item('2026-11-01', 'A')]);
  const next = snap([item(null, 'New without date'), item('2026-11-01', 'A')]);
  assert.deepEqual(diffPlans(prev, next).changes, []);
});

test('removed announcement is not reported', () => {
  const prev = snap([item('2026-11-01', 'A'), item('2026-10-30', 'B')]);
  const next = snap([item('2026-11-01', 'A')]);
  assert.deepEqual(diffPlans(prev, next).changes, []);
});

test('old record without titles counts as the first run', () => {
  const old = { plans: [{ name: 'Pro', input_price: 3 }] };
  const r = diffPlans(old, snap([item('2026-11-01', 'Model A')]));
  assert.equal(r.baseline, true);
  assert.deepEqual(r.changes, []);
});

test('toIsoDate: date formats', () => {
  assert.equal(toIsoDate('2026-11-09'), '2026-11-09');
  assert.equal(toIsoDate('November 9, 2026'), '2026-11-09');
  assert.equal(toIsoDate('Nov 5'), null);
  assert.equal(toIsoDate('something else'), null);
  assert.equal(toIsoDate(null), null);
});

test('normalizePlan: lowercase category and empty summary become null', () => {
  const p = normalizePlan({ title: ' Model A ', category: 'API', summary: '  ', date: '2026-11-01' });
  assert.equal(p.title, 'Model A');
  assert.equal(p.category, 'api');
  assert.equal(p.summary, null);
});

test('checkExtraction: invalid response gives an error', () => {
  assert.ok(checkExtraction(null, undefined));
  assert.ok(checkExtraction(null, { plans: 'oops' }));
});

test('checkExtraction: 0 announcements after announcements gives an error', () => {
  assert.ok(checkExtraction(snap([item('2026-11-01', 'A')]), { plans: [] }));
});

test('checkExtraction: 0 announcements on the first run is allowed', () => {
  assert.equal(checkExtraction(null, { plans: [] }), null);
});

test('checkExtraction: duplicate announcements give an error', () => {
  assert.ok(checkExtraction(null, snap([item('2026-11-01', 'A'), item('2026-11-01', 'a')])));
});

test('checkExtraction: announcement without title gives an error', () => {
  assert.ok(checkExtraction(null, snap([{ date: '2026-11-01', title: '' }])));
});

test('checkExtraction: many new at once no longer blocks', () => {
  const prev = snap([item('2026-11-01', 'A')]);
  const many = [item('2026-11-01', 'A')];
  for (let i = 1; i <= 11; i++) many.push(item('2026-11-02', `New ${i}`));
  assert.equal(checkExtraction(prev, snap(many)), null);
});

test('diffPlans: many new at once are marked as bulk and not reported', () => {
  const prev = snap([item('2026-11-01', 'A')]);
  const many = [item('2026-11-01', 'A')];
  for (let i = 1; i <= 11; i++) many.push(item('2026-11-02', `New ${i}`));
  const r = diffPlans(prev, snap(many));
  assert.equal(r.bulk, true);
  assert.equal(r.count, 11);
  assert.deepEqual(r.changes, []);
});

test('checkExtraction: normal extraction with one new announcement passes', () => {
  const prev = snap([item('2026-11-01', 'A')]);
  assert.equal(checkExtraction(prev, snap([item('2026-11-14', 'B'), item('2026-11-01', 'A')])), null);
});

test('summarize: new announcement with date and summary', () => {
  const text = summarize({ type: 'added', title: 'Acme Pro 2.0', date: '2026-11-14', summary: 'Released the new version.' });
  assert.equal(text, 'New announcement (2026-11-14): "Acme Pro 2.0". Released the new version.');
});

test('summarize: without date and summary', () => {
  assert.equal(summarize({ type: 'added', title: 'X', date: null, summary: null }), 'New announcement: "X".');
});

test('summarize: full stop at the end of the title is not doubled', () => {
  const text = summarize({ type: 'added', title: 'Acme Pro 2.0 is now available.', date: '2026-11-14', summary: null });
  assert.equal(text, 'New announcement (2026-11-14): "Acme Pro 2.0 is now available".');
});
